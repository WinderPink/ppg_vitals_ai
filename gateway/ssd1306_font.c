#define FONT_TABLE_LEN (sizeof(font_table) / sizeof(font_table[0]))

bool ssd1306_font_lookup(char c, uint8_t out_cols[5])
{
  for (uint32_t i = 0; i < FONT_TABLE_LEN; i++) {
    if (font_table[i].c == c) {
      memcpy(out_cols, font_table[i].cols, 5);
      return true;
    }
  }
  // Ký tự không có trong bảng -> vẽ ô trắng đặc để dễ nhận biết là thiếu font
  memset(out_cols, 0x7F, 5);
  return false;
}